#!/usr/bin/env python3
"""Build Dockerfile.local from a small temporary, explicitly allowlisted context."""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import tempfile
from collections.abc import Callable, Sequence

ROOT_FILES = ("Dockerfile.local", "pyproject.toml", "README.md", "LICENSE")
ROOT_TREES = ("unimem", "protocol")
EXTRA_FILES = (os.path.join("deploy", "docker", "local-entrypoint.sh"),)
EXCLUDED_DIRS = {".git", ".pytest_cache", "__pycache__"}
EXCLUDED_SUFFIXES = {".pyc", ".pyo"}


def _copy_file(source_root: str, relative_path: str, context_root: str) -> None:
    source = os.path.join(source_root, relative_path)
    if os.path.islink(source) or not os.path.isfile(source):
        raise ValueError("required Docker input is missing or not a regular file: " + relative_path)
    destination = os.path.join(context_root, relative_path)
    os.makedirs(os.path.dirname(destination), exist_ok=True)
    shutil.copy2(source, destination)


def _copy_tree(source_root: str, relative_path: str, context_root: str) -> None:
    source_tree = os.path.join(source_root, relative_path)
    if os.path.islink(source_tree) or not os.path.isdir(source_tree):
        raise ValueError("required Docker input is missing or not a directory: " + relative_path)

    for current, directories, filenames in os.walk(source_tree, topdown=True, followlinks=False):
        directories.sort()
        filenames.sort()
        kept_directories = []
        for directory in directories:
            source = os.path.join(current, directory)
            if os.path.islink(source):
                raise ValueError("symlinks are not allowed in the Docker context: " + source)
            if directory not in EXCLUDED_DIRS:
                kept_directories.append(directory)
        directories[:] = kept_directories

        relative_directory = os.path.relpath(current, source_root)
        destination_directory = os.path.join(context_root, relative_directory)
        os.makedirs(destination_directory, exist_ok=True)
        for filename in filenames:
            if any(filename.endswith(suffix) for suffix in EXCLUDED_SUFFIXES):
                continue
            source = os.path.join(current, filename)
            if os.path.islink(source):
                raise ValueError("symlinks are not allowed in the Docker context: " + source)
            if not os.path.isfile(source):
                raise ValueError("non-regular files are not allowed in the Docker context: " + source)
            shutil.copy2(source, os.path.join(destination_directory, filename))


def copy_allowlisted_context(source_root: str, context_root: str) -> None:
    """Copy only Dockerfile.local inputs, rejecting symlinks and generated bytecode."""
    source_root = os.path.abspath(source_root)
    context_root = os.path.abspath(context_root)
    if os.path.commonpath((source_root, context_root)) == source_root:
        raise ValueError("Docker build context must be outside the source checkout")

    os.makedirs(context_root, exist_ok=False)
    for relative_path in ROOT_FILES:
        _copy_file(source_root, relative_path, context_root)
    for relative_path in ROOT_TREES:
        _copy_tree(source_root, relative_path, context_root)
    for relative_path in EXTRA_FILES:
        _copy_file(source_root, relative_path, context_root)


def build_local_image(
    source_root: str,
    image_tag: str,
    docker_command: str = "docker",
    run: Callable[..., object] = subprocess.run,
) -> None:
    """Build an image and always remove its temporary context."""
    with tempfile.TemporaryDirectory(prefix="unimem-local-build-") as temporary_root:
        context_root = os.path.join(temporary_root, "context")
        copy_allowlisted_context(source_root, context_root)
        dockerfile = os.path.join(context_root, "Dockerfile.local")
        run(
            [docker_command, "build", "--tag", image_tag, "--file", dockerfile, context_root],
            check=True,
        )


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tag", default="unimem-local:dev", help="image tag to build")
    parser.add_argument("--docker", default="docker", help="Docker CLI executable")
    parser.add_argument(
        "--repo-root",
        default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        help="UniMem checkout containing Dockerfile.local",
    )
    args = parser.parse_args(argv)
    build_local_image(args.repo_root, args.tag, docker_command=args.docker)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
